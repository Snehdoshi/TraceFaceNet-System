export function Badge({ className, variant = "default", ...props }: React.HTMLAttributes<HTMLDivElement> & { variant?: "default" | "secondary" | "destructive" | "outline" | "success" | "warning" }) {
  return (
    <div
      className={cn(
        "inline-flex items-center rounded-full border px-2.5 py-0.5 text-xs font-semibold transition-colors focus:outline-none focus:ring-2 focus:ring-ring focus:ring-offset-2",
        {
          "border-transparent bg-primary/20 text-primary border-primary/30": variant === "default",
          "border-transparent bg-secondary text-secondary-foreground": variant === "secondary",
          "border-transparent bg-destructive/20 text-destructive border-destructive/30 shadow-[0_0_10px_rgba(239,68,68,0.2)]": variant === "destructive",
          "border-transparent bg-success/20 text-success border-success/30 shadow-[0_0_10px_rgba(34,197,94,0.2)]": variant === "success",
          "border-transparent bg-warning/20 text-warning border-warning/30": variant === "warning",
          "text-foreground": variant === "outline",
        },
        className
      )}
      {...props}
    />
  );
}

